export type MessageKey = keyof typeof M;

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = M[key][locale] ?? M[key].en;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function sessionReplayErrorMessage(error: unknown, locale: Locale): string | undefined {
  if (!(error instanceof Error) || error.name !== 'SessionReplayError') return undefined;
  const code = 'code' in error && typeof (error as { code: unknown }).code === 'string' ? (error as { code: string }).code : '';
  if (code === 'no-user-input') return t(locale, 'notReplayableNoUserInput');
  if (code === 'corrupt') return t(locale, 'notReplayableCorrupt');
  if (code === 'unreadable') return t(locale, 'notReplayableUnreadable');
  if (code === 'history-only') return t(locale, 'notReplayableHistoryOnly');
  if (code === 'source-missing') return t(locale, 'notReplayableCatalogOnly');
  if (code === 'pending') return t(locale, 'notReplayablePending');
  return error.message;
}

const HOST_EXPLANATION_KEYS = new Set<MessageKey>([
  'recoveryReportMissing',
  'recoverySourceChanged',
  'recoveryStagingInvalid',
  'recoveryPreflightFailed',
  'harnessTransient',
  'harnessAuthentication',
  'harnessProtocol',
  'harnessFailure',
]);

export function isHostExplanationKey(value: string): value is MessageKey {
  return HOST_EXPLANATION_KEYS.has(value as MessageKey);
}

export function formatRecoveryFailureSummary(
  locale: Locale,
  stage: string,
  detail?: { changedPathCount?: number; agentFailureKind?: string; explanationKey?: MessageKey },
): string {
  if (detail?.explanationKey) return t(locale, detail.explanationKey);
  if (detail?.agentFailureKind && (stage === 'agent_model_failed' || stage === 'agent_timeout')) return formatHarnessFailure(locale, 'recovery', detail.agentFailureKind);
  if (stage === 'source_tripwire_failed') return t(locale, 'recoverySourceChanged');
  if (stage === 'preflight_failed') return t(locale, 'recoveryPreflightFailed');
  if (stage === 'agent_invalid_output') return formatHarnessFailure(locale, 'recovery', 'protocol');
  if (stage === 'runner_crashed') return t(locale, 'harnessFailure');
  const noWorkspaceChange = stage === 'provider_validation_failed' && (detail?.changedPathCount ?? -1) === 0;
  const reason = noWorkspaceChange
    ? t(locale, 'recoveryReasonNoWorkspaceChange')
    : stage === 'provider_validation_failed' ? t(locale, 'recoveryStagingInvalid')
    : /budget/.test(stage) ? t(locale, 'recoveryReasonBudget')
    : stage === 'agent_model_failed' || stage === 'agent_timeout' ? t(locale, 'recoveryReasonModelFailed')
    : stage === 'agent_tool_failed' ? t(locale, 'recoveryReasonToolFailed')
    : t(locale, 'recoveryReasonGeneric');
  const code = noWorkspaceChange ? `${stage}; no_task_path_outcome` : stage;
  return t(locale, 'recoveryReasonWithCode', { reason, code });
}

export function formatHarnessFailure(locale: Locale, phase: 'probe' | 'recovery' | 'opening' | 'controller', kind: string): string {
  const stage = t(locale, phase === 'probe' ? 'harnessProbe' : phase === 'recovery' ? 'harnessRecovery' : phase === 'opening' ? 'harnessOpening' : 'harnessController');
  const reason = t(locale, ['transient_network', 'transient_upstream', 'timeout', 'rate_limited'].includes(kind) ? 'harnessTransient' : kind === 'authentication' ? 'harnessAuthentication' : kind === 'protocol' ? 'harnessProtocol' : 'harnessFailure');
  return `${stage}: ${reason} (${kind})`;
}

export function parseLocale(value: string | undefined): Locale | undefined {
  const normalized = value?.trim().toLowerCase();
  if (normalized === 'en' || normalized === 'english') return 'en';
  if (normalized === 'zh' || normalized === 'zh-cn' || normalized === 'chinese' || normalized === '中文') return 'zh';
  return undefined;
}

export function nextLocale(locale: Locale): Locale {
  return locale === 'en' ? 'zh' : 'en';
}

